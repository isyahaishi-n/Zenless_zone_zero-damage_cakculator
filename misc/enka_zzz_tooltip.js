	function formatCAL(text, level) {
		return text.replace(
			/\{CAL:(.+?),(.+?),(.+?)}/g,
			(match, expression, i, j) => {
				const parser = new exprEval.Parser();
				expression = expression.replace(/AvatarSkillLevel\(.\)/, level);
				const result = parser.evaluate(expression);
				return Number.parseFloat((result * i).toFixed(1));
			},
		);
	}

	function format(text, level = 1, terms = {}) {
		text = text.replaceAll("\\n", "<br>");
		text = text.replace(
			/<color=#([0-9A-Fa-f]{6})>(.*?)<\/color>/g,
			(match, colorCode, text) => {
				// Convert ARGB to RGBA for CSS
				const r = parseInt(colorCode.slice(0, 2), 16);
				const g = parseInt(colorCode.slice(2, 4), 16);
				const b = parseInt(colorCode.slice(4, 6), 16);
				const a = (parseInt("FF", 16) / 255).toFixed(2);
				const rgbaColor = `rgba(${r}, ${g}, ${b}, ${a})`;
				return `<span style="color: ${rgbaColor};">${text}</span>`;
			},
		);
		text = text.replace(/{LAYOUT_([A-Z]+)#(.*?)}/g, (_, layout, value) => {
			if (layout === "PC") {
				return value;
			}
			return "";
		});

		text = text.replace(/<IconMap:([A-Za-z_]+)>/g, (match, name) => {
			const svgIcon = svg[iconMap[name]];
			return `<svg xmlns="http://www.w3.org/2000/svg" class="textSvg" viewBox="${svgIcon.viewBox}">${svgIcon.content}</svg>`;
		});

		text = text.replaceAll(/\<Term:(\d+)>/g, (_, termId) => {
			return `<span style="text-decoration: underline; color: white;">${terms[termId.toString()].Title}</span>`;
		});

		text = text.replaceAll(
			/\{RUBY_[A-Z]#(?:[\u3040-\u309F\u30A0-\u30FF]*)\}/g,
			"",
		);

		text = formatCAL(text, level);

		if (text.length < 1 || text[0] != "#") return text;
		return text
			.slice(1)
			.replace(
				/{(\w+)}/g,
				(_, ...args) => KWARGS.get(args[0]) ?? `<${args[0]}>`,
			);
	}

	function getTerms(desc) {
		const matches = desc.match(/\<Term:(\d+)>/g) ?? [];
		return matches.map((m) => {
			return m.replace("<Term:", "").replace(">", "");
		});
	}

	function formatParam(template, skills, level) {
		template = template.replace(
			/\{Skill:(\d+), Prop:(\d+)}/g,
			(match, skillId, propId) => {
				const skill = skills[skillId];
				var formattedValue;

				if (propId == 1001) {
					formattedValue =
						skill.DamageValue + skill.DamageGrowth * level;
				} else if (propId == 1002) {
					formattedValue = skill.DazeValue + skill.DazeGrowth * level;
				}
				return (formattedValue / 100).toFixed(1) + "%";
			},
		);
		template = formatCAL(template, level + 1);

		template = template.replace(/\{([^}]*)\}/g, (match, expression) => {
			const parser = new exprEval.Parser();
			expressionFound = true;
			const result = parser.evaluate(expression.replaceAll("%", ""));
			return result.toFixed(1) + "%";
		});

		return template;
	}

	function formatStat(value, name = "") {
		value = Math.round(value);
		if (name.includes("Ratio") || name.includes("Crit"))
			value = value.toFixed(1) / 100 + "%";
		else if (name.includes("Sp")) {
			value = value.toFixed(1) / 100;
		} else if (value >= 1000) {
			value = Array.from(value + "");
			value.splice(-3, 0, ",");
			value = value.join("");
		}
		return value;
	}

	function propSimpleName(fullname) {
		simpleName = fullname.split("_").slice(0, -1).join("_");
		return simpleName;
	}

